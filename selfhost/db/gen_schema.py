#!/usr/bin/env python3
"""Generate Postgres DDL from a Base44 export's data/_entity_schemas.json.

Usage: python3 gen_schema.py <_entity_schemas.json> [out.sql] [rls.json]

Tables and columns keep Base44's exact names (quoted), so the data adapter can map
entity.field straight to table.column. Constraints (NOT NULL, enums) are not
enforced: legacy rows don't always satisfy them. Row-level-security rules are
written to rls.json for the application layer to enforce; they are not SQL policies.
"""
import json, sys

TYPES = {"string": "text", "number": "double precision", "integer": "bigint",
         "boolean": "boolean", "array": "jsonb", "object": "jsonb"}
BASE_COLS = [("id", "text primary key"), ("created_date", "timestamptz"),
             ("updated_date", "timestamptz"), ("created_by", "text"),
             ("created_by_id", "text"), ("is_sample", "boolean")]


def q(name):
    return '"' + name.replace('"', '""') + '"'


def col_type(spec):
    t = spec.get("type")
    f = spec.get("format")
    if t == "string" and f == "date-time":
        return "timestamptz"
    if t == "string" and f == "date":
        return "date"
    if t == "date-time":
        return "timestamptz"
    return TYPES.get(t, "jsonb")


def main():
    src = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else "schema.sql"
    rls_out = sys.argv[3] if len(sys.argv) > 3 else "rls.json"
    entities = json.load(open(src))
    lines, rls = ["-- Generated by gen_schema.py. Do not edit by hand.", ""], {}
    for e in sorted(entities, key=lambda e: e["entity_name"]):
        name, sch = e["entity_name"], e["entity_schema"]
        if name == "User":
            continue  # accounts live in the auth tables
        cols = [f"  {q(c)} {t}" for c, t in BASE_COLS]
        for field, spec in sch.get("properties", {}).items():
            if field in dict(BASE_COLS):
                continue
            cols.append(f"  {q(field)} {col_type(spec)}")
        cols.append("  \"_extra\" jsonb")  # fields in the data but not the schema
        lines.append(f"create table {q(name)} (\n" + ",\n".join(cols) + "\n);")
        idx = ["created_date", "created_by_id"] + [
            f for f in sch.get("properties", {}) if f.endswith("_id") and f != "created_by_id"]
        for f in idx:
            lines.append(f"create index {q(f'{name}_{f}_idx')} on {q(name)} ({q(f)});")
        lines.append("")
        rls[name] = sch.get("rls")
    open(out, "w").write("\n".join(lines))
    json.dump(rls, open(rls_out, "w"), indent=1)
    print(f"{len(rls)} tables -> {out}; rls rules -> {rls_out}")


main()
